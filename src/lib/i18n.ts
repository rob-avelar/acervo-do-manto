export function langForCountry(country?: string | null): Lang {
  const c = (country ?? "").toUpperCase();
  if (c === "BR" || c === "PT") return "pt";
  if (c === "ES") return "es";
  if (c === "NL" || c === "BE") return "nl";
  return "en";
}
